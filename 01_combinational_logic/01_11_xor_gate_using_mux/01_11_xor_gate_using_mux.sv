module xor_gate_using_mux
(
    input  a,
    input  b,
    output o
);

wire inv_or ;

mux mux_inv 
(
	  .sel(b),
	  .d0(1'b1),
	  .d1(1'b0),
	  .y(inv_or)
);

mux mux_or
(
    .d0(b),
    .d1(inv_or),
    .sel(a),
    .y(o)
);


endmodule
